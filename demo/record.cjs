/** Requires `npm run demo` and Playwright Chromium. Records real UI interactions.
 * RUN: npm install; npx playwright install chromium; npm run record
 * Optional CHROMIUM_PATH selects an existing Chrome binary.
 */
const { chromium }=require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict')
const out=path.resolve(__dirname,'../.recordings')
fs.mkdirSync(out,{recursive:true})
;(async()=>{
 const reset=await fetch('http://127.0.0.1:4175/demo/reset',{method:'POST'}).then(r=>r.json())
 assert.equal(reset.code,0)
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH})
 const setup=await browser.newContext({viewport:{width:1280,height:900},timezoneId:'Asia/Shanghai'})
 const login=await setup.newPage()
 await login.goto('http://127.0.0.1:5173/#/pages/subpages/login/index',{waitUntil:'networkidle'})
 await login.getByText('同意并继续',{exact:true}).click()
 await login.getByText('开发测试登录',{exact:true}).click()
 await login.getByText('认证态',{exact:true}).waitFor()
 await login.goto('http://127.0.0.1:5174/',{waitUntil:'networkidle'})
 await login.getByPlaceholder('请输入管理员账号').fill('demo')
 await login.getByPlaceholder('请输入密码').fill('DemoOnly@2026')
 await login.getByPlaceholder('输入右侧字符').fill('DEMO')
 await login.getByRole('button',{name:'登录',exact:true}).click()
 await login.getByRole('heading',{name:'管理工作台'}).waitFor()
 const storageState=await setup.storageState()
 await setup.close()
 const context=await browser.newContext({viewport:{width:1920,height:1080},deviceScaleFactor:1,timezoneId:'Asia/Shanghai',storageState,recordVideo:{dir:out,size:{width:1920,height:1080}}})
 const page=await context.newPage()
 const errors=[],steps=[]
 page.on('pageerror',e=>errors.push(e.message))
 page.on('response',r=>{if(r.status()>=400)errors.push(`HTTP ${r.status()} ${r.url()}`)})
 await page.goto('http://127.0.0.1:4175/showcase',{waitUntil:'networkidle'})
 const app=page.frameLocator('#app')
 await app.getByText('一起去看星星 · 校园观星夜',{exact:true}).waitFor()
 await page.evaluate(()=>document.fonts.ready)
 await page.waitForTimeout(600)
 await page.screenshot({path:path.join(out,'cover.png')})
 const start=Date.now()
 await page.evaluate(()=>begin())
 async function at(second,label,action){
   await page.waitForTimeout(Math.max(0,start+second*1000-Date.now()))
   await action()
   const elapsed=(Date.now()-start)/1000
   assert(elapsed<second+5,`Scene '${label}' exceeded its timing budget`)
   steps.push({second,completed_at:elapsed,label});console.log(`PASS ${label} (${elapsed.toFixed(1)}s)`)
 }
 async function scene(title,desc,step,desktop=false){await page.evaluate(args=>scene(...args),[title,desc,step,desktop])}
 async function navigate(url){await page.locator('#app').evaluate((e,url)=>e.src=url,url)}
 await at(7,'打开活动详情',async()=>{
   await scene('发现感兴趣的<br>校园活动。','时间、地点、名额与活动介绍，<br>在一个页面清楚呈现。','02 / 活动详情')
   await app.getByText('一起去看星星 · 校园观星夜',{exact:true}).click()
   await app.getByText('去报名',{exact:true}).waitFor()
 })
 await at(14,'填写报名备注',async()=>{
   await scene('报名，<br>只需几步。','带出个人信息，填写备注，<br>提交后查看报名状态。','03 / 活动报名')
   await app.getByText('去报名',{exact:true}).click()
   const remark=app.locator('textarea')
   await remark.waitFor();await remark.pressSequentially('想学习星空摄影，会准时参加。',{delay:80})
 })
 await at(19,'提交报名成功',async()=>{
   const response=page.waitForResponse(r=>r.url().endsWith('/activity/register')&&r.request().method()==='POST')
   await app.getByText('提交报名',{exact:true}).click()
   assert.equal((await (await response).json()).data.status,'approved')
   await app.getByText('报名成功',{exact:true}).waitFor()
 })
 await at(23,'报名记录持久于本地服务内存',async()=>{
   await scene('参与进度，<br>随时可查。','“我的报名”集中查看活动状态，<br>减少重复询问与信息遗漏。','04 / 我的报名')
   await navigate('http://127.0.0.1:5173/#/pages/subpages/my-registrations/index')
   await app.getByText('已报名',{exact:true}).waitFor()
   await page.screenshot({path:path.join(out,'registration.png')})
 })
 await at(29,'招新动态表单交互',async()=>{
   await scene('招新报名，<br>适配不同社团。','按岗位配置生成报名表，<br>支持单选、多选与文本字段。','05 / 招新表单')
   await navigate('http://127.0.0.1:5173/#/pages/subpages/recruitment-register/index?id=rec-1')
   await app.getByText('活动策划部',{exact:true}).click()
   await app.locator('input').first().fill('喜欢天文，愿意参与校园科普活动。')
   await page.screenshot({path:path.join(out,'recruitment.png')})
 })
 await at(36,'管理工作台',async()=>{
   await scene('管理工作台 · 待办一目了然','从待办卡片直达审核，统一管理运营事项。','06',true)
   await navigate('http://127.0.0.1:5174/#/dashboard')
   await app.getByRole('heading',{name:'管理工作台'}).waitFor()
 })
 await at(41,'打开待审活动',async()=>{
   await scene('活动审核 · 有确认，有反馈','查看待审核活动，确认通过后更新审核列表。','07',true)
   await app.getByRole('button',{name:/待审活动/}).click()
   await app.getByText('校园星空摄影工作坊',{exact:true}).waitFor()
   await page.screenshot({path:path.join(out,'review.png')})
   await app.getByRole('button',{name:'通过',exact:true}).click()
   await app.getByRole('button',{name:'确认通过',exact:true}).waitFor()
 })
 await at(46,'审核通过并验证列表更新',async()=>{
   const response=page.waitForResponse(r=>r.url().endsWith('/activity/review')&&r.request().method()==='POST')
   await app.getByRole('button',{name:'确认通过',exact:true}).click()
   assert.equal((await (await response).json()).data.activity.status,'approved')
   await app.locator('select:visible').selectOption('approved')
   await app.getByRole('button',{name:'查询',exact:true}).click()
   await app.getByText('校园星空摄影工作坊',{exact:true}).waitFor()
 })
 await at(51,'四维数据统计展示',async()=>{
   await scene('数据统计 · 看见运营全貌','用户、社团、活动、招新四个维度；画面数值为合成样例。','08',true)
   await navigate('http://127.0.0.1:5174/#/stats')
   await app.getByRole('heading',{name:'数据统计',exact:true}).waitFor()
   await app.getByText('128',{exact:true}).waitFor()
   await page.screenshot({path:path.join(out,'stats.png')})
 })
 await at(57,'项目入口',async()=>{
   await scene('ClubHub 社团星球 · 查看源码与运行说明','github.com/chenc55/ClubHub ｜ uni-app · Vue 3 · uniCloud','09',true)
 })
 await page.waitForTimeout(Math.max(0,start+60500-Date.now()))
 const tailStart=Date.now(), video=page.video()
 await context.close()
 const videoPath=await video.path()
 const recordedTailSeconds=(tailStart-start)/1000
 fs.writeFileSync(path.join(out,'recording-report.json'),JSON.stringify({videoPath,recordedTailSeconds,durationTarget:60,steps,errors,scope:'Real local browser interactions with synthetic in-memory API; no deployment or cloud acceptance'},null,2))
 await browser.close()
 assert.deepEqual(errors,[])
 console.log(`VIDEO ${videoPath}`)
})().catch(e=>{console.error(e);process.exit(1)})
